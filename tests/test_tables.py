import math

import pandas as pd

from inragwetrust.analysis import tables as tb

MODELS = ("llama", "mistral", "qwen")
METAS = ("consistency", "reliability")
BLOCKS = (("rho:type", 3, 22.2), ("prompt:type", 6, 45.3), ("rho:model", 2, 31.7), ("prompt:model", 4, 71.4))


def conf() -> dict[str, pd.DataFrame]:
    f1 = pd.DataFrame([{"family": "F1", "model": m, "estimate": 53.7, "ci_low": 41.8, "ci_high": 69.2,
                        "p_raw": 1e-200, "p_holm": 3e-200} for m in MODELS])
    f2 = pd.DataFrame([{"family": "F2", "test": t, "model": m, "meta": meta, "estimate_kind": "k",
                        "estimate": -0.024 if t == "a" else 0.044, "ci_low": -0.038 if t == "a" else 0.024,
                        "ci_high": -0.011 if t == "a" else 0.066, "p_raw": 0.01,
                        "p_holm": 0.6 if (t, m, meta) == ("a", "qwen", "reliability") else 0.02}
                       for t in "abc" for m in MODELS for meta in METAS])
    f3 = pd.DataFrame([{"family": "F3", "model": m, "estimate": 0.83, "ci_low": 0.77, "ci_high": 0.90,
                        "p_raw": 1e-5, "p_holm": 3e-5} for m in MODELS])
    f4 = pd.DataFrame([{"family": "F4", "block": b, "df": df, "estimate": x, "p_raw": 1e-5, "p_holm": 4e-5}
                       for b, df, x in BLOCKS])
    return {"f1": f1, "f2": f2, "f3": f3, "f4": f4}


def sens(change: tuple[str, str] | None = ("leaks", "f2")) -> dict[tuple[str, str], pd.DataFrame]:
    """Same schema as the real sensitivity CSVs: F4 has no CI columns."""
    out = {}
    for kind in tb.KINDS:
        for fam, d in conf().items():
            s = d.rename(columns={"estimate": "estimate_primary", "ci_low": "ci_low_primary",
                                  "ci_high": "ci_high_primary", "p_holm": "p_holm_primary"})
            s = s.drop(columns=[c for c in ("family", "df", "p_raw", "estimate_kind") if c in s.columns])
            s["estimate_sens"], s["p_holm_sens"] = s["estimate_primary"], s["p_holm_primary"]
            if fam != "f4":
                s["ci_low_sens"], s["ci_high_sens"] = s["ci_low_primary"], s["ci_high_primary"]
            s["conclusion_primary"] = s["conclusion_sens"] = "down"
            s["same_conclusion"] = True
            if change == (kind, fam):
                s.loc[0, ["conclusion_sens", "same_conclusion", "p_holm_sens"]] = ["n.s.", False, 0.2]
            out[(kind, fam)] = s
    return out


def test_number_and_p_formatting():
    assert tb.fmt_p(0.0004) == "$<0.001$" and tb.fmt_p(0.0123) == "0.012" and tb.fmt_p(math.nan) == "n.e."
    assert tb.num(-2.4, 1) == "$-$2.4" and tb.num(-0.0004, 1) == "0.0"


def test_confirmatory_rows_cover_all_28_tests_with_units():
    rows = tb.confirmatory_rows(conf())
    assert len(rows) == 28
    assert rows[0][4] == "53.7 [41.8, 69.2]" and rows[0][6] == "$<0.001$"
    assert rows[3][4] == "$-$2.4 [$-$3.8, $-$1.1]" and rows[3][2] == "cons."
    assert rows[21][4] == "0.83 [0.77, 0.90]"
    assert rows[24][4] == "$\\chi^2(3)=22.2$" and rows[24][1] == "--"


def test_verdict_counts_come_from_the_data():
    rows = tb.verdict_rows(conf())
    assert [r[0] for r in rows] == ["H1", "H2", "H3", "H4"]
    assert rows[2][1] == "supported" and "5 of 6" in rows[1][2]
    assert "3 of 3" in rows[2][2] and "4 of 4" in rows[3][2]


def test_robustness_counts_and_changed_rows():
    summary, changed = tb.robustness_rows(sens())
    assert summary[1] == ["F2/H2", "18", "18", "17"]
    assert summary[-1] == ["Total", "28", "28", "27"]
    assert len(changed) == 1 and "Llama-3.1-8B, cons." in changed[0][1] and changed[0][6] == "down $\\to$ n.s."


def test_f4_sensitivity_without_ci_columns():
    _, changed = tb.robustness_rows(sens(change=("flagged", "f4")))
    assert len(changed) == 1 and changed[0][2] == "$\\chi^2=22.2$" and "[" not in changed[0][2]


def test_robustness_without_changes_says_so():
    assert "No conclusion changed." in tb.render_robustness(sens(change=None))


def test_main_writes_three_tables(tmp_path):
    src, out = tmp_path / "in", tmp_path / "out"
    src.mkdir()
    for fam, d in conf().items():
        d.to_csv(src / f"confirmatory_{fam}.csv", index=False)
    for (kind, fam), d in sens().items():
        d.to_csv(src / f"sensitivity_{kind}_{fam}.csv", index=False)
    tb.main(["--results", str(src), "--out", str(out)])
    for name in ("tab_confirmatory", "tab_verdicts", "tab_robustness"):
        text = (out / f"{name}.tex").read_text()
        assert text.startswith("% Generated by") and "\\begin{table}" in text and "\\bottomrule" in text

def test_verdicts_fit_the_text_width():
    assert "llp{0.64\\linewidth}" in tb.render_verdicts.__code__.co_consts

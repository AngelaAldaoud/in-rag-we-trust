"""Paper tables (Block F4): LaTeX generated from the committed CSVs, never typed by hand (D272).
Run with:
    uv run python -m inragwetrust.analysis.tables
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from inragwetrust.analysis.figures import LABELS, RESULTS, need

TABLES = RESULTS / "tables"
FAMILIES = ("f1", "f2", "f3", "f4")
KINDS = {"flagged": "Flagged", "leaks": "Leaks"}
HYP = {"f1": "H1", "f2": "H2", "f3": "H3", "f4": "H4"}
META = {"consistency": "cons.", "reliability": "rel."}
TEST = {"a": r"$\Delta$ASR, $\rho>0$", "b": r"$\Delta$Acc, $\rho=0$", "c": r"$\Delta$Abst, $\rho=0$"}
BLOCK = {"rho:type": r"$\rho\times$type", "prompt:type": r"prompt$\times$type",
         "rho:model": r"$\rho\times$model", "prompt:model": r"prompt$\times$model"}
LABEL_COLS = {"f1": ["model"], "f2": ["test", "model", "meta"], "f3": ["model"], "f4": ["block"]}
SENS_COLS = ["estimate_primary", "p_holm_primary", "estimate_sens", "p_holm_sens", "conclusion_primary",
             "conclusion_sens", "same_conclusion"]
SENS_CI = ["ci_low_primary", "ci_high_primary", "ci_low_sens", "ci_high_sens"]
ALPHA = 0.05
HEADER = "% Generated by inragwetrust.analysis.tables from results/analysis/*.csv. Do not edit by hand.\n"


def num(x, digits: int) -> str:
    if pd.isna(x):
        return "--"
    x = float(x)
    if round(x, digits) == 0:
        x = 0.0
    return f"{x:.{digits}f}".replace("-", "$-$")


def ci(est, lo, hi, digits: int) -> str:
    s = num(est, digits)
    if pd.isna(lo) or pd.isna(hi):
        return s
    return f"{s} [{num(lo, digits)}, {num(hi, digits)}]"


def fmt_p(p) -> str:
    if pd.isna(p):
        return "n.e."
    return "$<0.001$" if p < 0.001 else f"{p:.3f}"


def estimate(fam: str, est, lo=None, hi=None) -> str:
    """F2 in percentage points, F4 as chi2 (no CI), odds ratios with 1 or 2 decimals."""
    if fam == "f4":
        return f"$\\chi^2={float(est):.1f}$"
    lo = float("nan") if lo is None else lo
    hi = float("nan") if hi is None else hi
    if fam == "f2":
        return ci(100 * est, 100 * lo, 100 * hi, 1)
    return ci(est, lo, hi, 1 if abs(est) >= 10 else 2)


def model_name(m) -> str:
    return LABELS.get(m, m) if isinstance(m, str) else "--"


def quantity(fam: str, r: pd.Series) -> str:
    if fam == "f1":
        return r"OR $\rho$ 0$\to$1"
    if fam == "f2":
        return TEST.get(r["test"], str(r.get("estimate_kind", r["test"])))
    if fam == "f3":
        return "OR flagged vs unflagged"
    return BLOCK.get(r["block"], str(r["block"]))


def describe(fam: str, r: pd.Series) -> str:
    parts = [model_name(r.get("model")), META.get(r.get("meta"), "--"), quantity(fam, r)]
    return ", ".join(p for p in parts if p != "--")


def tabular(header: list[str], rows: list[list[str]], align: str, rules: bool = False) -> str:
    lines = [f"\\begin{{tabular}}{{{align}}}", r"\toprule", " & ".join(header) + r" \\", r"\midrule"]
    prev = None
    for r in rows:
        if rules and prev is not None and r[0] != prev:
            lines.append(r"\midrule")
        lines.append(" & ".join(r) + r" \\")
        prev = r[0]
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


def table_env(caption: str, label: str, bodies: list[str], size: str = r"\small") -> str:
    body = "\n\\par\\medskip\n".join(bodies)
    return (f"{HEADER}\\begin{{table}}[t]\n\\centering\n{size}\n\\caption{{{caption}}}\\label{{{label}}}\n"
            f"{body}\n\\end{{table}}\n")


def confirmatory_rows(conf: dict[str, pd.DataFrame]) -> list[list[str]]:
    rows = []
    for fam in FAMILIES:
        d = conf[fam]
        cols = ["df", "estimate"] if fam == "f4" else ["estimate", "ci_low", "ci_high"]
        need(d, LABEL_COLS[fam] + cols + ["p_raw", "p_holm"], f"confirmatory_{fam}")
        for _, r in d.iterrows():
            if fam == "f4":
                est = f"$\\chi^2({int(r['df'])})={float(r['estimate']):.1f}$"
            else:
                est = estimate(fam, r["estimate"], r["ci_low"], r["ci_high"])
            rows.append([f"{fam.upper()}/{HYP[fam]}", model_name(r.get("model")), META.get(r.get("meta"), "--"),
                         quantity(fam, r), est, fmt_p(r["p_raw"]), fmt_p(r["p_holm"])])
    return rows


def verdict_rows(conf: dict[str, pd.DataFrame]) -> list[list[str]]:
    """Verdict labels are the D263 decision; every count in the evidence is computed from the CSVs."""
    a = conf["f2"][conf["f2"]["test"] == "a"]
    k2 = int(((a["p_holm"] < ALPHA) & (a["estimate"] < 0)).sum())
    f3, f4 = conf["f3"], conf["f4"]
    k3 = int(((f3["p_holm"] < ALPHA) & (f3["estimate"] < 1)).sum())
    k4 = int((f4["p_holm"] < ALPHA).sum())
    return [
        ["H1", "partly supported",
         "F1 significant for all three models; the steepest step follows the 2--2 tie at $\\rho=0.5$ "
         "rather than occurring at it (D262); the closed-book part agrees."],
        ["H2", "partly supported",
         f"{k2} of {len(a)} $\\Delta$ASR reductions significant; not mainly at intermediate $\\rho$ for Mistral "
         "and Llama-reliability; accuracy cost at $\\rho=0$ not small for Mistral; reductions come mostly "
         "from abstention."],
        ["H3", "supported",
         f"Association only: flagged answers poisoned less often for {k3} of {len(f3)} models; flag rates stay "
         "above the $\\rho=0$ baseline at $\\rho=1$ for Llama and Qwen."],
        ["H4", "partly supported",
         f"{k4} of {len(f4)} interaction blocks significant; no consistent poison-type effect descriptively "
         "(weak manipulation); models differ."],
    ]


def robustness_rows(sens: dict[tuple[str, str], pd.DataFrame]) -> tuple[list[list[str]], list[list[str]]]:
    summary, changed = [], []
    for fam in FAMILIES:
        same = {}
        for kind in KINDS:
            d = sens[(kind, fam)]
            need(d, LABEL_COLS[fam] + SENS_COLS + ([] if fam == "f4" else SENS_CI), f"sensitivity_{kind}_{fam}")
            same[kind] = (int(d["same_conclusion"].astype(bool).sum()), len(d))
            for _, r in d[~d["same_conclusion"].astype(bool)].iterrows():
                changed.append([f"{KINDS[kind]} · {fam.upper()}", describe(fam, r),
                                estimate(fam, r["estimate_primary"], r.get("ci_low_primary"), r.get("ci_high_primary")),
                                fmt_p(r["p_holm_primary"]),
                                estimate(fam, r["estimate_sens"], r.get("ci_low_sens"), r.get("ci_high_sens")),
                                fmt_p(r["p_holm_sens"]), f"{r['conclusion_primary']} $\\to$ {r['conclusion_sens']}"])
        summary.append([f"{fam.upper()}/{HYP[fam]}", str(same["flagged"][1]), str(same["flagged"][0]),
                        str(same["leaks"][0])])
    total = [sum(int(r[i]) for r in summary) for i in (1, 2, 3)]
    summary.append(["Total"] + [str(t) for t in total])
    return summary, changed


def render_confirmatory(conf: dict[str, pd.DataFrame]) -> str:
    body = tabular(["Family", "Model", "Prompt", "Quantity", "Estimate [95\\% CI]", "$p$", "$p_{\\mathrm{Holm}}$"],
                   confirmatory_rows(conf), "lllllrr", rules=True)
    caption = ("Confirmatory tests of the frozen analysis plan. F1 and F3: odds ratios from GEE logistic models "
               "clustered by question (F3: odds of a poisoned answer when flagged vs unflagged, an association). "
               "F2: paired meta-prompt minus plain differences in percentage points, exact McNemar test, "
               "question-clustered bootstrap CI. F4: Wald $\\chi^2$ of interaction blocks. Holm correction within "
               "each family, two-sided $\\alpha=0.05$. ``--'': pooled over prompts.")
    return table_env(caption, "tab:confirmatory", [body])


def render_verdicts(conf: dict[str, pd.DataFrame]) -> str:
    body = tabular(["", "Verdict", "Evidence"], verdict_rows(conf), "llp{10cm}", rules=True)
    caption = "Hypothesis verdicts, assigned by a rule fixed before the tests (D250)."
    return table_env(caption, "tab:verdicts", [body])


def render_robustness(sens: dict[tuple[str, str], pd.DataFrame]) -> str:
    summary, changed = robustness_rows(sens)
    part1 = tabular(["Family", "Conclusions", "Same without flagged", "Same without leaks"], summary, "lrrr")
    rows = changed or [[r"\multicolumn{7}{l}{No conclusion changed.}"]]
    part2 = tabular(["Analysis", "Test", "Primary", "$p_{\\mathrm{Holm}}$", "Sensitivity", "$p_{\\mathrm{Holm}}$",
                     "Conclusion"], rows, "lllrlrl")
    caption = ("Robustness (exploratory): confirmatory conclusions (direction and significance after Holm) "
               "recomputed without the audit-flagged questions and without the leak questions. Bottom: every "
               "conclusion that changes.")
    return table_env(caption, "tab:robustness", [part1, part2], size=r"\footnotesize")


def load(results: Path) -> tuple[dict[str, pd.DataFrame], dict[tuple[str, str], pd.DataFrame]]:
    conf = {f: pd.read_csv(results / f"confirmatory_{f}.csv") for f in FAMILIES}
    sens = {(k, f): pd.read_csv(results / f"sensitivity_{k}_{f}.csv") for k in KINDS for f in FAMILIES}
    return conf, sens


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", default=str(RESULTS))
    ap.add_argument("--out", default=str(TABLES))
    a = ap.parse_args(argv)
    conf, sens = load(Path(a.results))
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for name, text in (("tab_confirmatory", render_confirmatory(conf)), ("tab_verdicts", render_verdicts(conf)),
                       ("tab_robustness", render_robustness(sens))):
        (out / f"{name}.tex").write_text(text, encoding="utf-8")
        print("Written", out / f"{name}.tex")
    summary, changed = robustness_rows(sens)
    total = summary[-1]
    print(f"Confirmatory rows: {len(confirmatory_rows(conf))}")
    print(f"Unchanged without flagged: {total[2]}/{total[1]}; without leaks: {total[3]}/{total[1]}")
    for r in changed:
        print("Changed:", r[0], "|", r[1], "|", r[6])


if __name__ == "__main__":
    main()
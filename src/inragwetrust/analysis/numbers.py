OUT = RESULTS / "numbers.tex"
MODEL = {"llama": "Llama", "mistral": "Mistral", "qwen": "Qwen"}
PROMPT = {"all": "All", "plain": "Plain", "consistency": "Cons", "reliability": "Rel"}
RHO = {0.0: "RhoZero", 0.25: "RhoQuarter", 0.5: "RhoHalf", 0.75: "RhoThreeQuarters", 1.0: "RhoOne"}
TEST = {"a": "Asr", "b": "Acc", "c": "Abst"}
METRIC = {"poisoned": "DAsr", "correct": "DAcc", "abstain": "DAbst", "nousable": "DNoUse"}
SCORING = {"rules": "Rules", "upper bound": "Upper"}
CB = {"target without passages": "TargetCB", "gold without passages": "GoldCB", "other": "OtherCB"}
POSITION = ("First", "Second", "Third", "Fourth", "Fifth")
OUTCOMES = ("Poisoned", "Abstain", "Correct")
ONES = ("Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten", "Eleven", "Twelve",
        "Thirteen", "Fourteen", "Fifteen", "Sixteen", "Seventeen", "Eighteen", "Nineteen")
TENS = {2: "Twenty", 3: "Thirty", 4: "Forty", 5: "Fifty", 6: "Sixty", 7: "Seventy", 8: "Eighty", 9: "Ninety"}
NAME = re.compile(r"[A-Za-z]+")
CHECKS = ("NQuestions", "FOneOrLlama", "AsrLlamaAllRhoOne", "AccLlamaAllRhoOne", "CrossRulesLlama",
          "CrossUpperLlama", "StepMaxLlama", "FTwoAsrSig", "FTwoAsrTests", "FThreeSig", "FFourSig",
          "FlagDiffLlamaRhoHalf", "TypeSpreadMax", "LeakQuestions", "MddMedian", "MddUnderpowered", "MddCells",
          "AuditCandidates", "AuditFlagged", "SensFlaggedSame", "SensLeaksSame", "SensConclusions")


def word(s) -> str:
    return "".join(p.capitalize() for p in re.findall(r"[A-Za-z]+", str(s)))


def number_word(n: int) -> str:
    """0..100 in words, for macro names (letters only)."""
    if not 0 <= n <= 100:
        raise ValueError(f"number_word expects 0..100, got {n}")
    if n == 100:
        return "Hundred"
    if n < 20:
        return ONES[n]
    tens, ones = divmod(n, 10)
    return TENS[tens] + ("" if ones == 0 else ONES[ones])


def rho_name(x) -> str:
    return RHO[round(float(x), 2)]


def group_name(g) -> str:
    g = str(g)
    if g == "closed-book":
        return "ClosedBook"
    if g == "retrieval":
        return "Retrieval"
    if g.startswith("rho="):
        return rho_name(g[4:])
    return word(g)


def eff_name(b) -> str:
    """Effective-rho bin of a BM25 context, named by its value in hundredths (0.33 -> EffThirtyThree)."""
    try:
        x = float(b)
    except (TypeError, ValueError):
        return "EffNone"
    if np.isnan(x):
        return "EffNone"
    return "Eff" + number_word(int(round(100 * x)))


def yes_no(v) -> str:
    return "Yes" if str(v).strip().lower() in ("true", "1", "yes") else "No"


def num(x, digits: int = 1) -> str:
    if x is None or pd.isna(x):
        return "--"
    x = float(x)
    if round(x, digits) == 0:
        x = 0.0
    return f"{x:.{digits}f}".replace("-", r"\ensuremath{-}")


def pct(x, digits: int = 1) -> str:
    return num(x if x is None or pd.isna(x) else 100 * float(x), digits)


def pval(p) -> str:
    if p is None or pd.isna(p):
        return "--"
    return r"\ensuremath{<}0.001" if p < 0.001 else f"{p:.3f}"


def rho_val(x) -> str:
    return "none" if x is None or pd.isna(x) else f"{float(x):.2f}"


def integer(x) -> str:
    return str(int(x))


class Macros:
    def __init__(self) -> None:
        self.items: dict[str, str] = {}
        self.sections: list[tuple[str, list[str]]] = []

    def section(self, title: str) -> None:
        self.sections.append((title, []))

    def add(self, name: str, value: str) -> None:
        if not NAME.fullmatch(name):
            raise ValueError(f"invalid macro name {name!r}: letters only")
        if name in self.items:
            raise ValueError(f"duplicate macro {name}")
        if not self.sections:
            self.section("Numbers")
        self.items[name] = value
        self.sections[-1][1].append(name)

    def trio(self, name: str, est, lo, hi, fmt) -> None:
        self.add(name, fmt(est))
        self.add(name + "Lo", fmt(lo))
        self.add(name + "Hi", fmt(hi))

    def tex(self) -> str:
        lines = ["% Generated by inragwetrust.analysis.numbers from results/analysis/*.csv. Do not edit by hand.",
                 f"% {len(self.items)} macros. Percentages and points carry no % sign; Lo/Hi = 95% CI bounds."]
        for title, names in self.sections:
            lines.append(f"\n% --- {title}")
            lines += [f"\\newcommand{{\\{n}}}{{{self.items[n]}}}" for n in names]
        return "\n".join(lines) + "\n"


def ratio_fmt(est):
    digits = 1 if abs(float(est)) >= 10 else 2
    return lambda v: num(v, digits)


def descriptives(M: Macros, d: pd.DataFrame) -> None:
    need(d, ["model", "prompt", "rho", "asr", "asr_lo", "asr_hi", "acc", "acc_lo", "acc_hi", "flag", "flag_lo",
             "flag_hi"], "descriptive_by_rho")
    M.section("Descriptives: rates by model, prompt and rho (percent, Wilson 95% CI)")
    for _, r in d.iterrows():
        base = MODEL[r["model"]] + PROMPT[r["prompt"]] + rho_name(r["rho"])
        for col, short in (("asr", "Asr"), ("acc", "Acc"), ("flag", "Flag")):
            M.trio(short + base, r[col], r[f"{col}_lo"], r[f"{col}_hi"], pct)
    a = d[d["prompt"] == "all"]
    M.section("Ranges over models, all prompts (percent)")
    for col, short in (("asr", "Asr"), ("acc", "Acc")):
        for rho in (0.0, 1.0):
            v = a.loc[a["rho"].round(2) == rho, col]
            M.add(f"{short}Range{rho_name(rho)}Min", pct(v.min()))
            M.add(f"{short}Range{rho_name(rho)}Max", pct(v.max()))
    M.section("Largest ASR step between neighbouring rho levels, all prompts (points)")
    for m, g in a.groupby("model"):
        g = g.sort_values("rho")
        steps = g["asr"].diff().to_numpy()[1:]
        i = int(np.argmax(steps))
        M.add("StepMax" + MODEL[m], pct(steps[i]))
        M.add("StepFrom" + MODEL[m], rho_val(g["rho"].iloc[i]))
        M.add("StepTo" + MODEL[m], rho_val(g["rho"].iloc[i + 1]))


def confirmatory(M: Macros, conf: dict[str, pd.DataFrame]) -> None:
    f1, f2, f3, f4 = (conf[k] for k in ("f1", "f2", "f3", "f4"))
    need(f1, ["model", "estimate", "ci_low", "ci_high", "p_raw", "p_holm"], "confirmatory_f1")
    need(f2, ["test", "model", "meta", "estimate", "ci_low", "ci_high", "p_raw", "p_holm"], "confirmatory_f2")
    need(f3, ["model", "n", "n_flagged", "asr_flagged", "asr_unflagged", "estimate", "ci_low", "ci_high", "p_raw",
              "p_holm"], "confirmatory_f3")
    need(f4, ["block", "df", "estimate", "p_raw", "p_holm"], "confirmatory_f4")
    M.section("F1 (H1): odds ratio rho 0 -> 1, GEE clustered by question")
    for _, r in f1.iterrows():
        m = MODEL[r["model"]]
        M.trio("FOneOr" + m, r["estimate"], r["ci_low"], r["ci_high"], ratio_fmt(r["estimate"]))
        M.add("FOneP" + m, pval(r["p_raw"]))
        M.add("FOnePHolm" + m, pval(r["p_holm"]))
    M.section("F2 (H2): meta-prompt minus plain (points), exact McNemar, Holm within F2")
    for _, r in f2.iterrows():
        name = "FTwo" + TEST[r["test"]] + MODEL[r["model"]] + PROMPT[r["meta"]]
        M.trio(name, r["estimate"], r["ci_low"], r["ci_high"], pct)
        M.add(name + "P", pval(r["p_raw"]))
        M.add(name + "PHolm", pval(r["p_holm"]))
    sig = f2["p_holm"] < ALPHA
    for test, short, direction in (("a", "AsrSig", -1), ("b", "AccDown", -1), ("c", "AbstUp", 1)):
        t = f2["test"] == test
        M.add("FTwo" + short, integer((t & sig & (np.sign(f2["estimate"]) == direction)).sum()))
        M.add("FTwo" + TEST[test] + "Tests", integer(t.sum()))
    M.section("F3 (H3): odds ratio poisoned when flagged vs unflagged (association)")
    for _, r in f3.iterrows():
        m = MODEL[r["model"]]
        M.trio("FThreeOr" + m, r["estimate"], r["ci_low"], r["ci_high"], ratio_fmt(r["estimate"]))
        M.add("FThreeP" + m, pval(r["p_raw"]))
        M.add("FThreePHolm" + m, pval(r["p_holm"]))
        M.add("FThreeAsrFlagged" + m, pct(r["asr_flagged"]))
        M.add("FThreeAsrUnflagged" + m, pct(r["asr_unflagged"]))
        M.add("FThreeNFlagged" + m, integer(r["n_flagged"]))
        M.add("FThreeN" + m, integer(r["n"]))
    M.add("FThreeSig", integer(((f3["p_holm"] < ALPHA) & (f3["estimate"] < 1)).sum()))
    M.section("F4 (H4): Wald chi2 of interaction blocks")
    for _, r in f4.iterrows():
        b = word(r["block"])
        M.add("FFourChi" + b, num(r["estimate"], 1))
        M.add("FFourDf" + b, integer(r["df"]))
        M.add("FFourP" + b, pval(r["p_raw"]))
        M.add("FFourPHolm" + b, pval(r["p_holm"]))
    M.add("FFourSig", integer((f4["p_holm"] < ALPHA).sum()))
    M.add("FFourBlocks", integer(len(f4)))


def crossover(M: Macros, cr: pd.DataFrame) -> None:
    need(cr, ["model", "prompt", "scoring", "crossover"], "explore_crossover")
    M.section("Crossover: first tested rho with ASR above Acc (exploratory)")
    for _, r in cr[cr["prompt"] == "all"].iterrows():
        M.add("Cross" + SCORING[r["scoring"]] + MODEL[r["model"]], rho_val(r["crossover"]))
    per = cr[cr["prompt"] != "all"]
    M.add("CrossCurves", integer(len(per)))
    M.add("CrossCurvesAtThreeQuarters", integer((per["crossover"].round(2) == 0.75).sum()))


def closed_book(M: Macros, cb: pd.DataFrame) -> None:
    need(cb, ["model", "n", "correct", "correct_lo", "correct_hi", "poisoned", "abstain"], "explore_closed_book")
    M.section("Closed-book (no passages)")
    n = cb["n"].unique()
    if len(n) != 1:
        raise ValueError(f"closed-book n differs between models: {n}")
    M.add("NQuestions", integer(n[0]))
    for _, r in cb.iterrows():
        m = MODEL[r["model"]]
        M.trio("ClosedAcc" + m, r["correct"], r["correct_lo"], r["correct_hi"], pct)
        M.add("ClosedAsr" + m, pct(r["poisoned"]))
        M.add("ClosedAbst" + m, pct(r["abstain"]))
    M.add("ClosedAccMin", pct(cb["correct"].min()))
    M.add("ClosedAccMax", pct(cb["correct"].max()))


def prompt_effects(M: Macros, pe: pd.DataFrame) -> None:
    need(pe, ["model", "rho", "meta", "metric", "delta", "lo", "hi"], "explore_prompt_effects")
    M.section("Meta-prompt minus plain by rho (points, clustered bootstrap CI, exploratory)")
    for _, r in pe.iterrows():
        M.trio(METRIC[r["metric"]] + MODEL[r["model"]] + PROMPT[r["meta"]] + rho_name(r["rho"]),
               r["delta"], r["lo"], r["hi"], pct)


def flag_baseline(M: Macros, fb: pd.DataFrame) -> None:
    need(fb, ["model", "rho", "baseline", "delta", "lo", "hi"], "explore_flag_baseline")
    M.section("Flag rate: rho=0 baseline (percent) and difference from it (points)")
    for m, g in fb.groupby("model"):
        M.add("FlagBase" + MODEL[m], pct(g["baseline"].iloc[0]))
        for _, r in g.iterrows():
            M.trio("FlagDiff" + MODEL[m] + rho_name(r["rho"]), r["delta"], r["lo"], r["hi"], pct)


def type_model(M: Macros, tm: pd.DataFrame) -> None:
    need(tm, ["model", "poison_type", "rho", "n", "poisoned", "poisoned_lo", "poisoned_hi"], "explore_type_model")
    M.section("ASR by poison type (percent, Wilson CI); spread = largest gap between types at one rho (points)")
    spreads = []
    for m, g in tm.groupby("model"):
        for _, r in g.iterrows():
            M.trio("TypeAsr" + MODEL[m] + word(r["poison_type"]) + rho_name(r["rho"]), r["poisoned"],
                   r["poisoned_lo"], r["poisoned_hi"], pct)
        spread = g.groupby("rho")["poisoned"].agg(lambda s: s.max() - s.min()).max()
        spreads.append(spread)
        M.add("TypeSpread" + MODEL[m], pct(spread))
        M.add("TypeAsrPooled" + MODEL[m], pct((g["poisoned"] * g["n"]).sum() / g["n"].sum()))
    M.add("TypeSpreadMax", pct(max(spreads)))


def transitions(M: Macros, tr: pd.DataFrame) -> None:
    need(tr, ["model", "meta", "direction", "other_outcome", "share"], "explore_transitions")
    d = tr[tr["direction"].str.startswith("plain Poisoned")]
    M.section("Answers poisoned under plain: outcome under the meta-prompt (percent, exploratory)")
    stay = []
    for (m, meta), g in d.groupby(["model", "meta"]):
        s = g.set_index("other_outcome")["share"]
        named = {o: float(s.get(o, 0.0)) for o in OUTCOMES}
        named["Other"] = max(float(s.sum()) - sum(named.values()), 0.0)
        for o, v in named.items():
            M.add("Trans" + MODEL[m] + PROMPT[meta] + o, pct(v))
        stay.append(named["Poisoned"])
    M.add("TransStayMin", pct(min(stay)))
    M.add("TransStayMax", pct(max(stay)))


def bracket(M: Macros, br: pd.DataFrame) -> None:
    need(br, ["model", "group", "correct", "correct_plus", "poisoned", "poisoned_plus"], "explore_bracket")
    M.section("Accuracy bracket: rule-based vs judge-based upper bound (percent)")
    for _, r in br.iterrows():
        base = MODEL[r["model"]] + group_name(r["group"])
        for col, short in (("correct", "BrAcc"), ("correct_plus", "BrAccPlus"), ("poisoned", "BrAsr"),
                           ("poisoned_plus", "BrAsrPlus")):
            M.add(short + base, pct(r[col]))
    rho = br[br["group"].astype(str).str.startswith("rho=")]
    gap_acc, gap_asr = rho["correct_plus"] - rho["correct"], rho["poisoned_plus"] - rho["poisoned"]
    M.add("BrAccGapMin", pct(gap_acc.min()))
    M.add("BrAccGapMax", pct(gap_acc.max()))
    M.add("BrAsrGapMax", pct(gap_asr.max()))


def no_answer(M: Macros, na: pd.DataFrame) -> None:
    need(na, ["model", "no_answer", "no_answer_truncated", "no_answer_stopped", "cap_hits_all"], "explore_no_answer")
    M.section("NoAnswer and its sub-reasons (percent of all responses)")
    for _, r in na.iterrows():
        m = MODEL[r["model"]]
        M.add("NoAnswer" + m, pct(r["no_answer"]))
        M.add("NoAnswerTrunc" + m, pct(r["no_answer_truncated"]))
        M.add("NoAnswerStop" + m, pct(r["no_answer_stopped"]))
        M.add("CapHits" + m, pct(r["cap_hits_all"]))


def hallucination(M: Macros, h: pd.DataFrame) -> None:
    need(h, ["model", "group", "hall_any", "hall_strict_any", "precision", "miss_rate"], "explore_hallucination")
    M.section("Hallucination (percent of all responses; detector precision and miss rate)")
    for _, r in h.iterrows():
        base = MODEL[r["model"]] + group_name(r["group"])
        M.add("Hall" + base, pct(r["hall_any"]))
        M.add("HallStrict" + base, pct(r["hall_strict_any"]))
    with_passages = h.loc[h["group"] != "closed-book", "hall_any"]
    M.add("HallMin", pct(with_passages.min()))
    M.add("HallMax", pct(with_passages.max()))
    M.add("HallPrecision", str(h["precision"].iloc[0]))
    M.add("HallMiss", str(h["miss_rate"].iloc[0]))


def em_f1(M: Macros, e: pd.DataFrame) -> None:
    need(e, ["model", "group", "em", "f1"], "explore_em_f1")
    M.section("Exact match and token F1 against the gold answer (percent)")
    for _, r in e.iterrows():
        base = MODEL[r["model"]] + group_name(r["group"])
        M.add("Em" + base, pct(r["em"]))
        M.add("TokF" + base, pct(r["f1"]))


def prior_belief(M: Macros, p: pd.DataFrame) -> None:
    need(p, ["model", "cb_group", "rho", "n_questions", "poisoned", "poisoned_lo", "poisoned_hi"],
         "explore_prior_belief")
    M.section("ASR by closed-book answer (percent, question-clustered CI); PriorN = questions")
    for (m, g), d in p.groupby(["model", "cb_group"]):
        cb = CB.get(g, word(g))
        M.add("PriorN" + MODEL[m] + cb, integer(d["n_questions"].iloc[0]))
        for _, r in d.iterrows():
            M.trio("PriorAsr" + MODEL[m] + cb + rho_name(r["rho"]), r["poisoned"], r["poisoned_lo"],
                   r["poisoned_hi"], pct)
    known = p[(p["cb_group"] == "gold without passages") & (p["rho"].round(2) == 1.0)]["poisoned"]
    M.add("PriorGoldAsrRhoOneMin", pct(known.min()))
    M.add("PriorGoldAsrRhoOneMax", pct(known.max()))


def retrieval(M: Macros, rt: pd.DataFrame) -> None:
    need(rt, ["model", "eff_bin", "n", "poisoned", "poisoned_lo", "poisoned_hi"], "explore_retrieval_eff_rho")
    M.section("BM25 retrieval by effective rho, named in hundredths (percent, clustered CI); "
              "RetrShare = share of retrieval responses")
    for m, g in rt.groupby("model"):
        total = g["n"].sum()
        for _, r in g.iterrows():
            e = eff_name(r["eff_bin"])
            M.trio("RetrAsr" + MODEL[m] + e, r["poisoned"], r["poisoned_lo"], r["poisoned_hi"], pct)
            M.add("RetrShare" + MODEL[m] + e, pct(r["n"] / total))


def position(M: Macros, pos: pd.DataFrame, orig: pd.DataFrame) -> None:
    need(pos, ["model", "first_position", "poisoned", "poisoned_lo", "poisoned_hi"], "explore_position")
    need(orig, ["model", "first_is_original", "poisoned", "poisoned_lo", "poisoned_hi"], "explore_original_first")
    M.section("Position of the single poisoned passage at rho=0.25 (percent, clustered CI)")
    for _, r in pos.iterrows():
        M.trio("PosAsr" + MODEL[r["model"]] + POSITION[int(r["first_position"])], r["poisoned"], r["poisoned_lo"],
               r["poisoned_hi"], pct)
    for _, r in orig.iterrows():
        M.trio("OrigFirstAsr" + MODEL[r["model"]] + yes_no(r["first_is_original"]), r["poisoned"],
               r["poisoned_lo"], r["poisoned_hi"], pct)


def leaks(M: Macros, lk: pd.DataFrame) -> None:
    need(lk, ["model", "leak_any", "n_questions", "poisoned", "poisoned_lo", "poisoned_hi"], "explore_leaks")
    M.section("Leak questions: ASR with and without a leak (percent, clustered CI)")
    lk = lk.assign(leak=lk["leak_any"].map(yes_no))
    n = lk.loc[lk["leak"] == "Yes", "n_questions"].unique()
    if len(n) != 1:
        raise ValueError(f"leak-question count differs between models: {n}")
    M.add("LeakQuestions", integer(n[0]))
    for m, g in lk.groupby("model"):
        s = g.set_index("leak")
        for yn in ("Yes", "No"):
            M.trio("LeakAsr" + MODEL[m] + yn, s.loc[yn, "poisoned"], s.loc[yn, "poisoned_lo"],
                   s.loc[yn, "poisoned_hi"], pct)
        M.add("LeakDiff" + MODEL[m], pct(s.loc["No", "poisoned"] - s.loc["Yes", "poisoned"]))


def mdd(M: Macros, md: pd.DataFrame) -> None:
    need(md, ["mdd", "power_5pt"], "explore_mdd")
    M.section("Minimum detectable difference per cell (points) and power for a 5-point difference")
    M.add("MddMedian", pct(md["mdd"].median()))
    M.add("MddCells", integer(len(md)))
    M.add("MddUnderpowered", integer((md["power_5pt"] < 0.8).sum()))
    M.add("MddNoPower", integer(md["power_5pt"].isna().sum()))


def audit(M: Macros, dec: pd.DataFrame, flagged: pd.DataFrame) -> None:
    need(dec, ["gold_error", "comparison"], "audit_decisions")
    M.section("Audit of the main set (D188)")
    M.add("AuditCandidates", integer(len(dec)))
    M.add("AuditFlagged", integer(len(flagged)))
    M.add("AuditGoldErrors", integer(dec["gold_error"].map(yes_no).eq("Yes").sum()))
    M.add("AuditComparison", integer(dec["comparison"].map(yes_no).eq("Yes").sum()))


def sensitivity(M: Macros, sens) -> None:
    summary, _ = robustness_rows(sens)
    total = summary[-1]
    M.section("Robustness: conclusions unchanged without flagged / leak questions")
    M.add("SensConclusions", total[1])
    M.add("SensFlaggedSame", total[2])
    M.add("SensLeaksSame", total[3])


def build(results: Path = RESULTS) -> Macros:
    results = Path(results)

    def r(name: str) -> pd.DataFrame:
        return pd.read_csv(results / f"{name}.csv")

    conf, sens = load(results)
    M = Macros()
    closed_book(M, r("explore_closed_book"))
    descriptives(M, r("descriptive_by_rho"))
    confirmatory(M, conf)
    crossover(M, r("explore_crossover"))
    prompt_effects(M, r("explore_prompt_effects"))
    flag_baseline(M, r("explore_flag_baseline"))
    type_model(M, r("explore_type_model"))
    transitions(M, r("explore_transitions"))
    bracket(M, r("explore_bracket"))
    no_answer(M, r("explore_no_answer"))
    hallucination(M, r("explore_hallucination"))
    em_f1(M, r("explore_em_f1"))
    prior_belief(M, r("explore_prior_belief"))
    retrieval(M, r("explore_retrieval_eff_rho"))
    position(M, r("explore_position"), r("explore_original_first"))
    leaks(M, r("explore_leaks"))
    mdd(M, r("explore_mdd"))
    audit(M, r("audit_decisions"), r("flagged_questions"))
    sensitivity(M, sens)
    return M


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", default=str(RESULTS))
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args(argv)
    M = build(Path(a.results))
    Path(a.out).write_text(M.tex(), encoding="utf-8")
    print(f"Written {a.out}: {len(M.items)} macros in {len(M.sections)} sections")
    for name in CHECKS:
        print(f"  \\{name} = {M.items[name]}")


if __name__ == "__main__":
    main()